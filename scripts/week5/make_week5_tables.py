"""Populate two Week 5 LaTeX tables, reusing Week 4 report's documented values.
Missing Week 5 values remain '--' rather than being invented.
"""
import json
from pathlib import Path

R = Path("week5_results")
REPORT_DIR = Path(".")
W4 = {
    "YOLO11n": dict(size=5.21, mean=11.33, median=6.63, p95=14.19,
                    fps=88.27, e2e=21.15, e2e_fps=47.29,
                    ram=499.63, peak_ram=609.30, cpu=70.13),
    "YOLO26n": dict(size=5.13, mean=10.41, median=7.53, p95=14.12,
                    fps=96.03, e2e=18.13, e2e_fps=55.16,
                    ram=614.32, peak_ram=677.02, cpu=77.34),
}


def get_json(path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def value(name, key):
    s = get_json(R / f"{name.lower()}_onnx_summary.json")
    resource = get_json(R / f"{name.lower()}_onnx_isolated_resources.json")
    fields = {
        "size": (s, "model_size_mib"),
        "mean": (s, "mean_inference_ms"),
        "median": (s, "median_inference_ms"),
        "p95": (s, "p95_inference_ms"),
        "fps": (s, "model_fps"),
        "e2e": (s, "mean_end_to_end_ms"),
        "e2e_fps": (s, "pipeline_fps"),
        "ram": (resource, "mean_ram_mb"),
        "peak_ram": (resource, "peak_ram_mb"),
        "cpu": (resource, "mean_cpu_percent"),
    }
    src, column = fields[key]
    return src.get(column)


def fmt(number):
    return f"{number:.2f}" if isinstance(number, (int, float)) else "--"


def cells(name, key):
    return [fmt(W4[name][key]), fmt(value(name, key))]


rows = [
    ("Model file size (MiB)", "size"),
    ("Mean inference latency (ms)", "mean"),
    ("Median inference latency (ms)", "median"),
    ("P95 inference latency (ms)", "p95"),
    ("Derived model-only FPS", "fps"),
    ("Mean prediction-call latency (ms)", "e2e"),
    ("Derived prediction-call FPS", "e2e_fps"),
    ("Mean process RAM (MiB)", "ram"),
    ("Peak process RAM (MiB)", "peak_ram"),
    ("Mean process CPU (\\%)", "cpu"),
]
latex = [
    "% AUTO-GENERATED by make_week5_tables.py; do not manually insert invented values.",
    "% Week 4 historical measurements: PyTorch FP32 MPS (Apple GPU).",
    "% Week 5 measurements: ONNX Runtime FP32 CPUExecutionProvider.",
    "% CPU/RAM Week 4 values are taken from Week 4 report Table 2 (isolated resource runs),",
    "% NOT the mixed-process original benchmark_pytorch.csv sampling.",
    "\\begin{table}[htbp]",
    "\\centering",
    "\\small",
    "\\setlength{\\tabcolsep}{4pt}",
    "\\resizebox{\\linewidth}{!}{%",
    "\\begin{tabular}{lrrrr}",
    "\\hline",
    "Metric & 11n PT/MPS & 11n ORT/CPU & 26n PT/MPS & 26n ORT/CPU \\\\ ",
    "\\hline",
]
for label, key in rows:
    vals = cells("YOLO11n", key) + cells("YOLO26n", key)
    latex.append(label + " & " + " & ".join(vals) + " \\\\ ")
latex += [
    "\\hline",
    "\\end{tabular}%",
    "}",
    "\\caption{Historical Week 4 PyTorch MPS versus Week 5 ONNX Runtime CPU. Because execution providers differ, this is a configuration-level comparison, not a controlled runtime speedup experiment.}",
    "\\label{tab:week5_historical}",
    "\\end{table}",
    "",
    "\\begin{table}[htbp]",
    "\\centering",
    "\\small",
    "\\resizebox{\\linewidth}{!}{%",
    "\\begin{tabular}{lrr}",
    "\\hline",
    "Metric & YOLO11n ORT CPU & YOLO26n ORT CPU \\\\ ",
    "\\hline",
]
for label, key in rows:
    latex.append(label + " & " + " & ".join(fmt(value(n, key)) for n in ["YOLO11n", "YOLO26n"]) + " \\\\ ")
latex += [
    "\\hline",
    "\\end{tabular}%",
    "}",
    "\\caption{YOLO11n versus YOLO26n under ONNX Runtime FP32 CPUExecutionProvider.}",
    "\\label{tab:week5_onnx_models}",
    "\\end{table}",
    "",
]
out = REPORT_DIR / "week5_comparison_generated.tex"
out.write_text("\n".join(latex), encoding="utf-8")
print("Generated:", out)
print("Missing data appears as -- until benchmark files are produced.")
